"""## 03 — Feature Engineering com TF-IDF

O **TF-IDF** (*Term Frequency – Inverse Document Frequency*) transforma cada transcrição em um vetor
numérico, onde cada dimensão é uma palavra do vocabulário. O peso de um termo cresce quanto mais ele
aparece **naquela** reunião (TF) e diminui quanto mais ele aparece em **todas** as reuniões (IDF).
O resultado: termos que distinguem uma reunião das demais recebem peso alto; termos genéricos, peso baixo.

### Justificativa dos parâmetros escolhidos
| Parâmetro | Valor | Por quê |
|-----------|-------|---------|
| `ngram_range` | `(1, 2)` | Captura unigramas e bigramas. `risco churn` ou `modulo rh` carregam mais sinal juntos do que separados. |
| `min_df` | `2` | Ignora termos que aparecem em só 1 reunião — provável ruído idiossincrático. |
| `max_df` | `0.85` | Descarta termos presentes em mais de 85% dos docs — quase stopwords no nosso domínio. |
| `sublinear_tf` | `True` | Usa `1 + log(tf)` em vez de `tf` puro, suavizando o efeito de repetições. |

Em um corpus pequeno como o nosso, esses limiares evitam que o vetorizador crie milhares de colunas
inúteis e concentra a matriz nos termos realmente discriminativos.
"""

