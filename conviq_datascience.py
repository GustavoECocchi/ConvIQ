"""## 02 — Ingestão e preparação do texto

Antes de extrair *features*, o texto precisa ser **normalizado**. Esta é a etapa de pré-processamento,
crítica em qualquer pipeline de NLP — texto sujo gera *features* ruins. Aplicamos, em ordem:

1. **Lowercase** — uniformiza maiúsculas/minúsculas (`Protheus` e `protheus` viram o mesmo token).
2. **Remoção de pontuação e números** — removemos símbolos que não carregam significado semântico.
3. **Remoção de acentos** — opcional, mas reduz a fragmentação do vocabulário em português.
4. **Remoção de stopwords** — palavras muito frequentes e pouco informativas (`de`, `a`, `que`...).
5. **Normalização de espaços** — colapsa múltiplos espaços em um só.

> Mantemos a coluna `texto` original e criamos uma nova coluna `texto_limpo`, para sempre podermos
> auditar a transformação.
"""

# Stopwords em portugues + termos genericos de conversa que nao agregam sinal
stop_pt = set(stopwords.words('portuguese'))
stop_extra = {"voces", "voce", "gente", "agora", "ainda", "muito", "bem", "ser",
              "ja", "so", "fica", "ficar", "vai", "ter", "tem", "preciso", "quero",
              "queremos", "estamos", "estou", "olha", "entao", "isso", "esse", "essa"}
stop_total = stop_pt | stop_extra

def remover_acentos(texto):
    nfkd = unicodedata.normalize('NFKD', texto)
    return ''.join(c for c in nfkd if not unicodedata.combining(c))

def limpar_texto(texto):
    texto = texto.lower()                              # 1. lowercase
    texto = remover_acentos(texto)                     # 3. remove acentos
    texto = re.sub(r'[^a-z\s]', ' ', texto)            # 2. remove pontuacao e numeros
    tokens = texto.split()
    tokens = [t for t in tokens if t not in stop_total and len(t) > 2]  # 4. stopwords + tokens curtos
    return ' '.join(tokens)                            # 5. normaliza espacos

