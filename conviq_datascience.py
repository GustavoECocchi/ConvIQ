# Deteccao de prospect: empresas que declaram nao ser clientes ainda
MARCAS_PROSPECT = ["somos prospect", "ainda nao usamos", "nao usamos nada",
                   "nao temos um sistema", "hoje nao temos"]

def eh_prospect(texto):
    t = remover_acentos(texto.lower())
    return any(marca in t for marca in MARCAS_PROSPECT)

df["is_prospect"] = df["texto"].apply(eh_prospect)
print("Reunioes identificadas como prospect (cliente sem contrato vigente):")
print(df.loc[df["is_prospect"], ["cliente", "tipo"]].to_string(index=False))

def avaliar_cenario(textos, alvo, nome_cenario):
    """Revetoriza e roda LOOCV nos dois modelos para um cenario de rotulagem."""
    vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2, max_df=0.85, sublinear_tf=True)
    X_cen = vec.fit_transform(textos)
    linhas = []
    candidatos = {
        "Naive Bayes": MultinomialNB(),
        "Logistic Regression": LogisticRegression(
            class_weight="balanced", max_iter=1000, random_state=42),
    }
    for nome, modelo in candidatos.items():
        pred = cross_val_predict(modelo, X_cen, alvo, cv=LeaveOneOut())
        linha = avaliar(alvo, pred, nome)
        linha["cenario"] = nome_cenario
        linha["n"] = len(alvo)
        linhas.append(linha)
    return linhas

# Cenario A - rotulo original
comparativo = avaliar_cenario(df["texto_limpo"], y, "A. Rotulo original")

# Cenario B - prospect forcado para Baixo
y_b = y.copy()
y_b[df["is_prospect"].values] = 0
comparativo += avaliar_cenario(df["texto_limpo"], y_b, "B. Prospect = Baixo")

# Cenario C - prospect removido da populacao
mantem = ~df["is_prospect"].values
comparativo += avaliar_cenario(
    df.loc[mantem, "texto_limpo"],
    y[mantem].reset_index(drop=True),
    "C. Prospect excluido",
)

tabela_cenarios = pd.DataFrame(comparativo)[
    ["cenario", "modelo", "n", "accuracy", "precision", "recall", "f1"]
]
print("\nComparacao dos cenarios de rotulagem (LOOCV):")
print(tabela_cenarios.round(3).to_string(index=False))

