"""## 05 — Introdução a Embeddings

### TF-IDF vs. Embeddings

| Aspecto | TF-IDF | Embeddings (Word2Vec, BERT, OpenAI...) |
|---------|--------|----------------------------------------|
| Representação | Vetor **esparso** do tamanho do vocabulário | Vetor **denso** de dimensão fixa (ex.: 300, 768, 1536) |
| Significado | Conta ocorrência de palavras | Captura **significado e contexto** semântico |
| Sinônimos | `caro` e `custoso` são dimensões diferentes | Ficam **próximos** no espaço vetorial |
| Contexto | Ignora ordem e contexto | `banco` (assento) ≠ `banco` (financeiro) com modelos contextuais |
| Custo | Leve, rápido, interpretável | Pesado, exige modelo pré-treinado |
| Dados | Funciona bem com pouco texto | Brilha com volume e nuance |

### Por que começamos com TF-IDF no ConvIQ?
Para um corpus pequeno e um MVP, o TF-IDF é **transparente, rápido e interpretável** — conseguimos
explicar exatamente por que um termo pesou. É a base sobre a qual treinamos os classificadores das
seções 09 e 10.

### Quando migrar para embeddings?
Quando o ConvIQ escalar para milhares de reuniões e precisar entender que *"achei caro"*,
*"tá salgado"* e *"fora do orçamento"* significam a **mesma** insatisfação de preço — algo que o
TF-IDF, baseado em correspondência exata de palavras, não captura. Embeddings também habilitam busca
semântica ("encontre reuniões parecidas com esta") e classificação mais robusta de sentimento.

### Demonstração: similaridade entre reuniões com TF-IDF
Como ponte conceitual, calculamos a **similaridade do cosseno** entre os vetores TF-IDF. É exatamente
a mesma operação que se faria com embeddings — só muda a qualidade da representação por baixo.
"""

